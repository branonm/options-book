// Package render turns the domain model into the wheel book's tables, as
// Markdown. Every figure comes from the book; nothing here computes money
// beyond simple products and sums of figures the book already holds.
package render

import (
	"fmt"
	"io"
	"sort"
	"strings"
	"time"

	"github.com/shopspring/decimal"

	"github.com/branonm/options-book/internal/format"
	"github.com/branonm/options-book/internal/ledger"
	"github.com/branonm/options-book/internal/rules"
	"github.com/branonm/options-book/internal/strategy/wheel"
)

const (
	Begin = "<!-- BEGIN GENERATED: wheel book -->"
	End   = "<!-- END GENERATED -->"
)

// WheelBook writes the generated section of the wheel book.
func WheelBook(w io.Writer, bk *wheel.Book, r *rules.Rules, rep wheel.Report, snapshotDir string) {
	asOfYear = bk.AsOf.Year()
	p := func(f string, a ...any) { fmt.Fprintf(w, f, a...) }
	p("%s\n", Begin)
	p("*Generated by `wheel book` from `%s` (as of %s; equity quotes %s). Do not edit by hand — regenerate.*\n\n",
		snapshotDir, bk.AsOf.Format("2006-01-02"), quoteStamp(bk.QuoteTime))

	checkin(p, rep)
	legs(p, bk, r)
	callAways(p, bk, r)
	positions(p, bk)
	breakevens(p, bk)
	concentration(p, bk, r)
	premium(p, bk, r)
	p("%s\n", End)
}

type printer func(string, ...any)

func quoteStamp(ts string) string {
	t, err := time.Parse(time.RFC3339Nano, ts)
	if err != nil {
		return "n/a"
	}
	loc, err := time.LoadLocation("America/New_York")
	if err != nil {
		return t.UTC().Format("2006-01-02 15:04 UTC")
	}
	return t.In(loc).Format("Mon 1/2 3:04 PM MST")
}

func table(p printer, head []string, rows [][]string) {
	p("| %s |\n", strings.Join(head, " | "))
	seps := make([]string, len(head))
	for i := range seps {
		seps[i] = "---"
	}
	p("|%s|\n", strings.Join(seps, "|"))
	for _, r := range rows {
		p("| %s |\n", strings.Join(r, " | "))
	}
	p("\n")
}

func acctLabel(a *wheel.Account) string {
	switch a.Name {
	case "roth":
		return "Roth"
	case "trad":
		return "Trad"
	}
	return a.Label
}

// asOfYear is set by WheelBook; expirations in that year print without it.
var asOfYear int

func short(exp string) string {
	t, err := time.Parse("2006-01-02", exp)
	if err != nil {
		return exp
	}
	if t.Year() == asOfYear {
		return t.Format("1/2")
	}
	return t.Format("1/2/06")
}

func checkin(p printer, rep wheel.Report) {
	p("## Check-in\n\n**%s · %s · %s passed.**\n\n", format.Plural(len(rep.Defects), "defect"), format.Plural(len(rep.Alerts), "alert"), format.Plural(rep.Passed, "check"))
	rows := func(fs []wheel.Finding) [][]string {
		var out [][]string
		for _, f := range fs {
			out = append(out, []string{f.Account, f.Check, f.Subject, f.Expected, f.Actual, f.Rule})
		}
		return out
	}
	if len(rep.Defects) > 0 {
		p("**Defects — fix the order**\n\n")
		table(p, []string{"Acct", "Check", "Subject", "Expected", "Live", "Rule"}, rows(rep.Defects))
	}
	if len(rep.Alerts) > 0 {
		p("**Alerts — judgment needed**\n\n")
		table(p, []string{"Acct", "Check", "Subject", "Limit", "Actual", "Rule"}, rows(rep.Alerts))
	}
}

type callRow struct {
	a *wheel.Account
	c *wheel.ShortCall
}

func allCalls(bk *wheel.Book) []callRow {
	var out []callRow
	for _, a := range bk.Accounts() {
		for _, b := range a.Blocks {
			for _, c := range b.Calls {
				out = append(out, callRow{a, c})
			}
		}
	}
	return out
}

func legs(p printer, bk *wheel.Book, r *rules.Rules) {
	calls := allCalls(bk)
	var n int64
	var rows [][]string
	for _, cr := range calls {
		c := cr.c
		n += c.Leg.OpenQty
		want := c.ExpectedCloser(r)
		closer, tif, mark := "none 🔴", "—", "🔴 → "+format.Price(want.Price)
		if len(c.Closers) > 0 {
			cl := c.Closers[0]
			closer, tif = format.Price(cl.Price), "`"+cl.Tif+"`"
			mark = "✅"
			if !cl.Price.Equal(want.Price) {
				mark = "🔴 → " + format.Price(want.Price)
			}
			if cl.Tif != want.Tif {
				tif += " 🔴"
			}
		}
		delta := "—"
		if c.Quote != nil {
			if dv, err := decimal.NewFromString(c.Quote.Delta.Text); err == nil {
				delta = dv.StringFixed(3)
				if itm, known := c.ITM(); known && itm {
					delta += " ITM"
				}
			}
		}
		rows = append(rows, []string{acctLabel(cr.a), fmt.Sprintf("%s $%sc ×%d", c.Leg.Key.Symbol, c.Leg.Key.Strike, c.Leg.OpenQty),
			short(c.Leg.Key.Expiry), format.Price(c.Leg.FillPerShare), format.USD0(c.Leg.Net), closer, mark, tif, delta, fmt.Sprint(c.DTE(bk))})
	}
	p("## Live legs — %d contracts\n\n", n)
	table(p, []string{"Acct", "Leg", "Expiry", "Fill", "Credit", "Closer", "Rule 10", "tif", "Δ", "DTE"}, rows)
	p("Fill is the blended fill per share; Rule 10 is %s × fill rounded to the tick.\n\n", r.CoveredCallCloser.FractionOfFill)

	var rungs []string
	for _, rg := range bk.Ladder() {
		rungs = append(rungs, fmt.Sprintf("%s = %d", short(rg.Expiry), rg.Contracts))
	}
	p("**Ladder:** %s\n\n", strings.Join(rungs, " · "))
}

func callAways(p printer, bk *wheel.Book, r *rules.Rules) {
	var rows [][]string
	for _, cr := range allCalls(bk) {
		ca := cr.c.CallAway(r, bk)
		if ca == nil {
			continue
		}
		rows = append(rows, []string{acctLabel(cr.a), cr.c.Leg.Key.String(), format.Signed(ca.ShareGain), format.Signed(ca.Premium),
			format.Signed(ca.Total), fmt.Sprint(ca.Days), format.USD0(ca.Capital), format.Pct(ca.Annualized)})
	}
	p("## If called (Rule 11)\n\n")
	table(p, []string{"Acct", "Leg", "Share gain at strike", "Block premium", "Total", "Days", "Capital", "Annualized"}, rows)
	p("Share gain = (strike − basis) × shares called. Block premium = the block's net premium including this leg, pro rata to shares called. Capital = basis × shares called. Annualized = total ÷ capital × 365 ÷ calendar days.\n\n")
}

func positions(p printer, bk *wheel.Book) {
	p("## Positions\n\n")
	bookTotal, bookUnreal := decimal.Zero, decimal.Zero
	for _, a := range bk.Accounts() {
		var head []string
		if pf := a.Portfolio(); pf != nil {
			for _, kv := range [][2]string{{"total", pf.TotalValue.Text}, {"equity", pf.EquityValue.Text}, {"cash", pf.Cash.Text}, {"buying power", pf.BuyingPower.Text}} {
				if v, err := decimal.NewFromString(kv[1]); err == nil {
					head = append(head, kv[0]+" "+format.USD(v))
					if kv[0] == "total" {
						bookTotal = bookTotal.Add(v)
					}
				}
			}
		}
		p("**%s:** %s\n\n", a.Label, strings.Join(head, " · "))
		var rows [][]string
		value, unreal := decimal.Zero, decimal.Zero
		for _, b := range sortedBlocks(a) {
			be := "—"
			if b.Premium.IsPositive() {
				be = format.Price(b.Breakeven)
			}
			price, val, un := "—", "—", "—"
			if b.HasPrice {
				v := b.Value()
				u := b.Price.Sub(b.Basis).Mul(decimal.NewFromInt(b.Shares))
				price, val, un = "$"+b.Price.String(), format.USD0(v), format.Signed(u)
				value, unreal = value.Add(v), unreal.Add(u)
			}
			note := ""
			if b.Shares%100 != 0 {
				note = " (odd lot: uncoverable)"
			}
			rows = append(rows, []string{b.Symbol, fmt.Sprint(b.Shares), format.Price(b.Basis), be, price, val, un + note})
		}
		rows = append(rows, []string{"**Total**", "", "", "", "", "**" + format.USD0(value) + "**", "**" + format.Signed(unreal) + "**"})
		table(p, []string{"Symbol", "Shares", "Basis", "Breakeven", "Price", "Value", "Unrealized"}, rows)
		bookUnreal = bookUnreal.Add(unreal)
	}
	p("**Book value %s. Share unrealized %s.** Breakeven is shown for blocks with premium (Rule 11).\n\n", format.USD0(bookTotal), format.Signed(bookUnreal))
}

func sortedBlocks(a *wheel.Account) []*wheel.Block {
	bs := append([]*wheel.Block{}, a.Blocks...)
	sort.SliceStable(bs, func(i, j int) bool { return bs[i].Value().GreaterThan(bs[j].Value()) })
	return bs
}

func breakevens(p printer, bk *wheel.Book) {
	var rows [][]string
	for _, a := range bk.Accounts() {
		for _, b := range sortedBlocks(a) {
			if !b.Premium.IsPositive() || b.Shares < 100 {
				continue
			}
			spot, gap := "—", "—"
			if b.HasPrice {
				spot = "$" + b.Price.String()
				gap = format.SignedPrice(b.Price.Sub(b.Breakeven))
			}
			rows = append(rows, []string{fmt.Sprintf("%s %s %d", acctLabel(a), b.Symbol, b.Shares), format.USD0(b.Premium),
				format.Price(b.Breakeven), format.Price(b.Basis.Sub(b.Breakeven)), spot, gap})
		}
	}
	p("## Breakevens (Rule 11)\n\n")
	table(p, []string{"Block", "Premium", "Breakeven", "Basis→BE band", "Spot", "Spot − BE"}, rows)
}

func concentration(p printer, bk *wheel.Book, r *rules.Rules) {
	for _, c := range r.ConcentrationCaps {
		var rows [][]string
		for _, pl := range bk.Pools {
			g, t := pl.CapShare(c)
			rows = append(rows, []string{pl.Name, format.USD0(g), format.USD0(t), share(g, t, c)})
		}
		g, t := bk.CapShare(c)
		rows = append(rows, []string{"**book**", format.USD0(g), format.USD0(t), share(g, t, c)})
		p("## Concentration%s — %s = %s\n\n", capRule(c), c.Name, strings.Join(c.Symbols, " + "))
		table(p, []string{"Pool", capTitle(c.Name), "Share value", capTitle(c.Name) + " share"}, rows)
	}
}

func capRule(c rules.ConcentrationCap) string {
	if c.Rule == 0 {
		return ""
	}
	return fmt.Sprintf(" (Rule %d)", c.Rule)
}

func capTitle(name string) string {
	if name == "" {
		return name
	}
	return strings.ToUpper(name[:1]) + name[1:]
}

func share(g, t decimal.Decimal, c rules.ConcentrationCap) string {
	if t.IsZero() {
		return "—"
	}
	s := g.Div(t)
	out := format.Pct(s)
	if s.GreaterThan(c.MaxShare) {
		out = "**" + out + "** (over " + format.Pct(c.MaxShare) + ")"
	}
	return out
}

func premium(p printer, bk *wheel.Book, r *rules.Rules) {
	p("## Premium ledger\n\n")
	var parts []string
	legs, profitable := 0, 0
	basisCredit := decimal.Zero
	var losses []string
	for _, a := range bk.Accounts() {
		l := a.Ledger
		parts = append(parts, fmt.Sprintf("%s %s (%d legs)", a.Label, format.USD0(l.Realized), l.RealizedLegs))
		legs += l.RealizedLegs
		profitable += l.ProfitableLegs
		basisCredit = basisCredit.Add(l.BasisCredit)
		for _, lg := range l.Legs {
			if lg.PreCampaign || lg.End == ledger.EndOpen || lg.Kind == ledger.KindAcquisitionPut || lg.Net.IsPositive() {
				continue
			}
			losses = append(losses, fmt.Sprintf("%s %s %s (%s)", acctLabel(a), lg.Key.String(), format.USD0(lg.Net), lg.ClosedAt))
		}
	}
	op := bk.OpenPremium(r)
	p("- **Realized:** %s · **combined %s**, %d closed legs, **%d profitable**.\n", strings.Join(parts, " · "), format.USD0(op.RealizedSoFar), legs, profitable)
	if len(losses) > 0 {
		p("- **Losing legs:** %s.\n", strings.Join(losses, "; "))
	}
	p("- **Excluded:** %s of acquisition-put credit carried in share basis (Rule 4a).\n", format.USD0(basisCredit))
	p("- **Open gross %s.** Open net **%s** at the live closers; **%s** at the Rule 10 closers.\n", format.USD0(op.Gross), format.USD0(op.NetAtLive), format.USD0(op.NetAtRule10))
	p("- **Expected total %s** (realized + open net at live closers).\n\n", format.USD0(op.RealizedSoFar.Add(op.NetAtLive)))
}

// Splice replaces the generated section of doc (between Begin and End) with
// section. It fails if the markers are missing or out of order, so it can
// never overwrite hand-written prose.
func Splice(doc, section string) (string, error) {
	i := strings.Index(doc, Begin)
	j := strings.Index(doc, End)
	if i < 0 || j < 0 || j < i {
		return "", fmt.Errorf("document has no %q … %q section", Begin, End)
	}
	if strings.Count(doc, Begin) != 1 || strings.Count(doc, End) != 1 {
		return "", fmt.Errorf("document has more than one generated section")
	}
	return doc[:i] + strings.TrimRight(section, "\n") + doc[j+len(End):], nil
}
